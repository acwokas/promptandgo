#!/usr/bin/env node
/**
 * build-tip-migration.mjs - turn a gated draft into a reviewable migration.
 *
 * WHY A MIGRATION FILE AND NOT A DIRECT INSERT
 * ----------------------------------------------
 * This machine has no production Supabase service-role key, and even if it
 * did, writing straight to a production database from a generation script is
 * exactly the kind of hard-to-reverse, shared-system action that should stop
 * for a human to look at first. The existing repo already has a convention
 * for this: the original seed content shipped as
 * supabase/migrations/20250911082436_..._insert-existing-blog-articles.sql.
 * This script follows that convention, so a draft becomes a normal,
 * diffable, git-reviewed migration that Adrian applies with
 * `supabase db push` when he is satisfied with it, exactly like any other
 * schema change in this repo.
 *
 * WHAT IT DOES
 * ------------
 * 1. Reads a draft JSON file (see content/tips/drafts/*.json for the shape).
 * 2. Runs it through gateTip(). On failure, prints every failure code and
 *    detail and exits 1. Nothing is written.
 * 3. On success, writes a timestamped migration under supabase/migrations/
 *    with a single INSERT into public.articles, plus a comment block
 *    recording every cited source and its access date for auditability.
 *
 * Usage:
 *   node scripts/content/build-tip-migration.mjs content/tips/drafts/<slug>.json
 *   node scripts/content/build-tip-migration.mjs content/tips/drafts/*.json
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { gateTip, describeVerdict } from './content-quality-gate.mjs';

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(__dirname, '..', '..');
const migrationsDir = resolve(repoRoot, 'supabase', 'migrations');

function sqlString(value) {
  if (value === null || value === undefined) return 'NULL';
  return `'${String(value).replace(/'/g, "''")}'`;
}

function sqlArray(values) {
  if (!Array.isArray(values) || values.length === 0) return 'ARRAY[]::text[]';
  return `ARRAY[${values.map((v) => sqlString(v)).join(', ')}]`;
}

function buildMigrationSql(draft) {
  const sourcesComment = (draft.sources || [])
    .map((s) => `--   - ${s.label}: ${s.url}${s.accessed ? ` (accessed ${s.accessed})` : ''}`)
    .join('\n');

  return `-- Tip article: ${draft.title}
-- Generated by scripts/content/build-tip-migration.mjs, passed gateTip() before this file was written.
-- Sources cited in the body:
${sourcesComment}
--
-- Review before applying. This does not run automatically; apply with
-- \`supabase db push\` once you are satisfied with the content.

INSERT INTO public.articles (
  title,
  slug,
  content,
  synopsis,
  thumbnail_url,
  published_date,
  is_published,
  focus_keyword,
  keyphrases,
  meta_description,
  meta_title
) VALUES (
  ${sqlString(draft.title)},
  ${sqlString(draft.slug)},
  ${sqlString(draft.body_html)},
  ${sqlString(draft.synopsis)},
  ${sqlString(draft.thumbnail_url ?? null)},
  ${sqlString(draft.published_date)},
  true,
  ${sqlString(draft.focus_keyword)},
  ${sqlArray(draft.keyphrases)},
  ${sqlString(draft.meta_description)},
  ${sqlString(draft.meta_title)}
)
ON CONFLICT (slug) DO NOTHING;
`;
}

function timestampFor(publishedDate) {
  // Migration filenames sort and apply in timestamp order, so this is stamped
  // from the draft's scheduled published_date (not wall-clock "now", which
  // this environment cannot call) to keep the staggered calendar's ordering
  // visible directly in the migrations directory listing.
  const d = new Date(publishedDate);
  if (Number.isNaN(d.getTime())) throw new Error(`draft.published_date is not a valid date: ${publishedDate}`);
  const pad = (n) => String(n).padStart(2, '0');
  return (
    `${d.getUTCFullYear()}${pad(d.getUTCMonth() + 1)}${pad(d.getUTCDate())}` +
    `${pad(d.getUTCHours())}${pad(d.getUTCMinutes())}${pad(d.getUTCSeconds())}`
  );
}

function processDraft(path) {
  const draft = JSON.parse(readFileSync(path, 'utf8'));
  const required = ['slug', 'title', 'meta_title', 'meta_description', 'synopsis', 'focus_keyword', 'body_html', 'published_date'];
  const missing = required.filter((k) => !draft[k]);
  if (missing.length) {
    console.error(`${path}: FAIL missing required field(s): ${missing.join(', ')}`);
    return false;
  }

  const verdict = gateTip(draft);
  console.log(`${path}: ${describeVerdict(verdict)}`);
  if (!verdict.ok) {
    for (const f of verdict.failures) console.error(`  - ${f.code}: ${f.detail}`);
    return false;
  }
  for (const w of verdict.warnings) console.warn(`  ! ${w}`);

  const outPath = resolve(migrationsDir, `${timestampFor(draft.published_date)}_tip_${draft.slug}.sql`);
  if (existsSync(outPath)) {
    console.error(`  refusing to overwrite existing migration: ${outPath}`);
    return false;
  }
  writeFileSync(outPath, buildMigrationSql(draft));
  console.log(`  wrote ${outPath}`);
  return true;
}

const args = process.argv.slice(2);
if (args.length === 0) {
  console.error('Usage: node scripts/content/build-tip-migration.mjs <draft.json> [more.json ...]');
  process.exit(1);
}

let allOk = true;
for (const path of args) {
  const ok = processDraft(resolve(path));
  allOk = allOk && ok;
}
process.exit(allOk ? 0 : 1);
